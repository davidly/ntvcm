; HELLO FOR THE ORIGINAL INTEL MAC80 8080 MACRO CROSS-ASSEMBLER.
; COMMENTS ARE UPPERCASE BECAUSE MAC80 LISTS LOWERCASE AS SPACES.
BDOS    EQU 5
PRSTR   EQU 9                  ; PRINT A STRING ENDING IN $
PRINT   MACRO ADR              ; CALL THE CP/M BDOS TO PRINT ADR
        LXI D,ADR
        MVI C,PRSTR
        CALL BDOS
        ENDM
        ORG 100H
        PRINT MSG
        RET                    ; BACK TO CP/M
MSG:    DB 'HELLO FROM MAC80!',13,10,'$'
        END
